import { useState } from 'react';
import type { AnalysisResult } from '../../types';

interface ExportPanelProps {
  analysis: AnalysisResult;
  onClose: () => void;
}

interface ExportFormat {
  id: string;
  name: string;
  description: string;
  icon: string;
  mimeType: string;
  extension: string;
}

const exportFormats: ExportFormat[] = [
  {
    id: 'json',
    name: 'JSON Report',
    description: 'Complete analysis data in JSON format for programmatic use',
    icon: '📄',
    mimeType: 'application/json',
    extension: 'json'
  },
  {
    id: 'csv',
    name: 'CSV Field Analysis',
    description: 'Field-level analysis data in CSV format for spreadsheet analysis',
    icon: '📊',
    mimeType: 'text/csv',
    extension: 'csv'
  },
  {
    id: 'markdown',
    name: 'Markdown Report',
    description: 'Human-readable report in Markdown format for documentation',
    icon: '📝',
    mimeType: 'text/markdown',
    extension: 'md'
  },
  {
    id: 'txt',
    name: 'Text Summary',
    description: 'Plain text summary of key findings and recommendations',
    icon: '📋',
    mimeType: 'text/plain',
    extension: 'txt'
  }
];

function generateJsonExport(analysis: AnalysisResult): string {
  const exportData = {
    analysis: {
      timestamp: new Date().toISOString(),
      version: '1.0.0',
      ...analysis
    },
    metadata: {
      exportedAt: new Date().toISOString(),
      exportFormat: 'json',
      tool: 'OpenSearch Document Complexity Analyzer'
    }
  };
  
  return JSON.stringify(exportData, null, 2);
}

function generateCsvExport(analysis: AnalysisResult): string {
  const headers = ['Field Path', 'Type', 'Depth', 'Complexity', 'Is Array'];
  const rows = analysis.fields?.map(field => [
    field.path,
    field.type,
    field.depth.toString(),
    field.complexity.toFixed(2),
    field.isArray ? 'Yes' : 'No'
  ]) || [];
  
  const csvContent = [headers, ...rows]
    .map(row => row.map(cell => `"${cell}"`).join(','))
    .join('\n');
  
  return csvContent;
}

function generateMarkdownExport(analysis: AnalysisResult): string {
  const date = new Date().toLocaleDateString();
  
  return `# OpenSearch Document Analysis Report

**Generated:** ${date}
**Tool:** OpenSearch Document Complexity Analyzer

## Executive Summary

- **Complexity Score:** ${analysis.complexityScore}/10
- **Storage Impact Score:** ${analysis.indexSizeScore}/10
- **Total Fields:** ${analysis.fieldCount}
- **Max Nesting Depth:** ${analysis.maxDepth}
- **Estimated Storage:** ${analysis.estimatedStorageMB.toFixed(1)} MB

## Field Type Distribution

${Object.entries(analysis.fieldTypes)
  .filter(([_, count]) => count > 0)
  .map(([type, count]) => `- **${type.charAt(0).toUpperCase() + type.slice(1)}:** ${count} fields`)
  .join('\n')}

## Key Findings

### Warnings
${analysis.warnings.length > 0 
  ? analysis.warnings.map(warning => `- ⚠️ ${warning}`).join('\n')
  : '- ✅ No warnings detected'
}

### Optimization Recommendations
${analysis.optimizations.length > 0
  ? analysis.optimizations.map(optimization => `- 💡 ${optimization}`).join('\n')
  : '- ✅ Document is already well-optimized'
}

## Field Analysis

${analysis.fields?.slice(0, 10).map(field => 
  `### ${field.path}
- **Type:** ${field.type}
- **Depth:** ${field.depth}
- **Complexity:** ${field.complexity.toFixed(2)}
- **Array:** ${field.isArray ? 'Yes' : 'No'}
`).join('\n') || 'No field details available'}

${analysis.fields && analysis.fields.length > 10 ? `\n*Showing top 10 fields. Total: ${analysis.fields.length} fields*` : ''}

## Conclusion

This analysis was generated by the OpenSearch Document Complexity Analyzer. For more information and optimization guidance, visit the OpenSearch documentation.
`;
}

function generateTextExport(analysis: AnalysisResult): string {
  const date = new Date().toLocaleDateString();
  
  return `OPENSEARCH DOCUMENT ANALYSIS REPORT
Generated: ${date}

SUMMARY
=======
Complexity Score: ${analysis.complexityScore}/10
Storage Impact: ${analysis.indexSizeScore}/10
Total Fields: ${analysis.fieldCount}
Max Depth: ${analysis.maxDepth}
Est. Storage: ${analysis.estimatedStorageMB.toFixed(1)} MB

FIELD TYPES
===========
${Object.entries(analysis.fieldTypes)
  .filter(([_, count]) => count > 0)
  .map(([type, count]) => `${type.toUpperCase()}: ${count}`)
  .join('\n')}

WARNINGS
========
${analysis.warnings.length > 0 
  ? analysis.warnings.map((warning, i) => `${i + 1}. ${warning}`).join('\n')
  : 'None detected'
}

RECOMMENDATIONS
===============
${analysis.optimizations.length > 0
  ? analysis.optimizations.map((opt, i) => `${i + 1}. ${opt}`).join('\n')
  : 'Document is already optimized'
}

END OF REPORT`;
}

function generateExportContent(format: string, analysis: AnalysisResult): string {
  switch (format) {
    case 'json':
      return generateJsonExport(analysis);
    case 'csv':
      return generateCsvExport(analysis);
    case 'markdown':
      return generateMarkdownExport(analysis);
    case 'txt':
      return generateTextExport(analysis);
    default:
      return generateJsonExport(analysis);
  }
}

export function ExportPanel({ analysis, onClose }: ExportPanelProps) {
  const [selectedFormat, setSelectedFormat] = useState<string>('json');
  const [isExporting, setIsExporting] = useState(false);
  const [exportStatus, setExportStatus] = useState<'idle' | 'success' | 'error'>('idle');

  const handleExport = async (format: ExportFormat) => {
    setIsExporting(true);
    setExportStatus('idle');

    try {
      // Simulate brief processing delay
      await new Promise(resolve => setTimeout(resolve, 500));
      
      const content = generateExportContent(format.id, analysis);
      const blob = new Blob([content], { type: format.mimeType });
      
      // Create download
      const url = URL.createObjectURL(blob);
      const link = document.createElement('a');
      link.href = url;
      link.download = `opensearch-analysis-${Date.now()}.${format.extension}`;
      document.body.appendChild(link);
      link.click();
      document.body.removeChild(link);
      URL.revokeObjectURL(url);
      
      setExportStatus('success');
    } catch (error) {
      console.error('Export failed:', error);
      setExportStatus('error');
    } finally {
      setIsExporting(false);
    }
  };

  const copyToClipboard = async (format: ExportFormat) => {
    try {
      const content = generateExportContent(format.id, analysis);
      await navigator.clipboard.writeText(content);
      setExportStatus('success');
      
      // Reset status after 3 seconds
      setTimeout(() => setExportStatus('idle'), 3000);
    } catch (error) {
      console.error('Copy failed:', error);
      setExportStatus('error');
      
      // Reset status after 3 seconds
      setTimeout(() => setExportStatus('idle'), 3000);
    }
  };

  const shareableUrl = () => {
    const params = new URLSearchParams({
      complexity: analysis.complexityScore.toString(),
      storage: analysis.indexSizeScore.toString(),
      fields: analysis.fieldCount.toString(),
      depth: analysis.maxDepth.toString(),
      types: Object.entries(analysis.fieldTypes)
        .filter(([_, count]) => count > 0)
        .map(([type, count]) => `${type}:${count}`)
        .join(',')
    });
    
    return `${window.location.origin}${window.location.pathname}?${params.toString()}`;
  };

  const copyShareableUrl = async () => {
    try {
      await navigator.clipboard.writeText(shareableUrl());
      setExportStatus('success');
      setTimeout(() => setExportStatus('idle'), 3000);
    } catch (error) {
      console.error('Copy URL failed:', error);
      setExportStatus('error');
      setTimeout(() => setExportStatus('idle'), 3000);
    }
  };

  return (
    <div className="bg-white dark:bg-gray-800 border border-gray-200 dark:border-gray-700 rounded-lg p-6 shadow-lg">
      <div className="flex items-center justify-between mb-6">
        <h3 className="text-lg font-semibold text-gray-900 dark:text-gray-100">
          Export Analysis Results
        </h3>
        <button
          onClick={onClose}
          className="text-gray-400 hover:text-gray-600 dark:hover:text-gray-200 transition-colors"
        >
          ✕
        </button>
      </div>

      {/* Status Messages */}
      {exportStatus === 'success' && (
        <div className="mb-4 p-3 bg-green-50 dark:bg-green-900/20 border border-green-200 dark:border-green-800 rounded-lg">
          <div className="flex items-center space-x-2">
            <span className="text-green-600 dark:text-green-400">✅</span>
            <span className="text-green-800 dark:text-green-200 text-sm">
              Export completed successfully!
            </span>
          </div>
        </div>
      )}

      {exportStatus === 'error' && (
        <div className="mb-4 p-3 bg-red-50 dark:bg-red-900/20 border border-red-200 dark:border-red-800 rounded-lg">
          <div className="flex items-center space-x-2">
            <span className="text-red-600 dark:text-red-400">❌</span>
            <span className="text-red-800 dark:text-red-200 text-sm">
              Export failed. Please try again.
            </span>
          </div>
        </div>
      )}

      {/* Export Formats */}
      <div className="space-y-4 mb-6">
        <h4 className="font-medium text-gray-900 dark:text-gray-100">
          Choose Export Format:
        </h4>
        
        <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
          {exportFormats.map((format) => (
            <div 
              key={format.id} 
              className={`p-4 border rounded-lg transition-colors cursor-pointer ${
                selectedFormat === format.id
                  ? 'border-indigo-300 bg-indigo-50 dark:bg-indigo-900/20 dark:border-indigo-600'
                  : 'border-gray-200 dark:border-gray-600 hover:border-gray-300 dark:hover:border-gray-500'
              }`}
              onClick={() => setSelectedFormat(format.id)}
            >
              <div className="flex items-start space-x-3">
                <span className="text-2xl flex-shrink-0">{format.icon}</span>
                <div className="flex-1 min-w-0">
                  <div className="font-medium text-gray-900 dark:text-gray-100">
                    {format.name}
                  </div>
                  <div className="text-sm text-gray-600 dark:text-gray-400 mt-1">
                    {format.description}
                  </div>
                </div>
                {selectedFormat === format.id && (
                  <span className="text-indigo-600 dark:text-indigo-400">✓</span>
                )}
              </div>
            </div>
          ))}
        </div>
      </div>

      {/* Export Actions */}
      <div className="grid grid-cols-1 sm:grid-cols-2 gap-4 mb-6">
        <button
          onClick={() => handleExport(exportFormats.find(f => f.id === selectedFormat)!)}
          disabled={isExporting}
          className="flex items-center justify-center space-x-2 px-4 py-3 bg-indigo-600 text-white rounded-lg hover:bg-indigo-700 disabled:bg-indigo-400 disabled:cursor-not-allowed transition-colors"
        >
          {isExporting ? (
            <>
              <div className="w-4 h-4 border-2 border-white border-t-transparent rounded-full animate-spin"></div>
              <span>Exporting...</span>
            </>
          ) : (
            <>
              <span>💾</span>
              <span>Download File</span>
            </>
          )}
        </button>
        
        <button
          onClick={() => copyToClipboard(exportFormats.find(f => f.id === selectedFormat)!)}
          className="flex items-center justify-center space-x-2 px-4 py-3 bg-gray-600 text-white rounded-lg hover:bg-gray-700 transition-colors"
        >
          <span>📋</span>
          <span>Copy to Clipboard</span>
        </button>
      </div>

      {/* Sharing Options */}
      <div className="border-t border-gray-200 dark:border-gray-700 pt-6">
        <h4 className="font-medium text-gray-900 dark:text-gray-100 mb-4">
          Share Analysis:
        </h4>
        
        <div className="space-y-3">
          <button
            onClick={copyShareableUrl}
            className="w-full flex items-center justify-center space-x-2 px-4 py-3 border border-gray-300 dark:border-gray-600 text-gray-700 dark:text-gray-300 rounded-lg hover:bg-gray-50 dark:hover:bg-gray-700 transition-colors"
          >
            <span>🔗</span>
            <span>Copy Shareable URL</span>
          </button>
          
          <div className="text-xs text-gray-500 dark:text-gray-400 text-center">
            Share a URL with key analysis metrics (no sensitive data included)
          </div>
        </div>
      </div>

      {/* Preview Section */}
      <div className="border-t border-gray-200 dark:border-gray-700 pt-6 mt-6">
        <details className="group">
          <summary className="cursor-pointer font-medium text-gray-900 dark:text-gray-100 mb-3 flex items-center space-x-2 hover:text-indigo-600 dark:hover:text-indigo-400 transition-colors">
            <span>👁️ Preview Export Content</span>
            <svg className="w-4 h-4 transition-transform group-open:rotate-180" fill="currentColor" viewBox="0 0 20 20">
              <path fillRule="evenodd" d="M5.293 7.293a1 1 0 011.414 0L10 10.586l3.293-3.293a1 1 0 111.414 1.414l-4 4a1 1 0 01-1.414 0l-4-4a1 1 0 010-1.414z" clipRule="evenodd" />
            </svg>
          </summary>
          
          <div className="bg-gray-50 dark:bg-gray-900 border border-gray-200 dark:border-gray-700 rounded-lg p-4 max-h-60 overflow-y-auto">
            <pre className="text-xs text-gray-800 dark:text-gray-200 whitespace-pre-wrap font-mono">
              {generateExportContent(selectedFormat, analysis).slice(0, 2000)}
              {generateExportContent(selectedFormat, analysis).length > 2000 && '\n\n... (truncated for preview)'}
            </pre>
          </div>
        </details>
      </div>
    </div>
  );
}